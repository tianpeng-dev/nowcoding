#!/usr/bin/env node

import { buildRcFixture } from './rc-fixture.mjs';

const API_TOKEN_PATTERN = /^nc_live_[A-Za-z0-9_-]{32}$/;

const baseUrl = process.env.NOWCODING_SMOKE_BASE_URL;
const token = process.env.NOWCODING_SMOKE_TOKEN;

if (!baseUrl) {
  console.error('Set NOWCODING_SMOKE_BASE_URL, for example https://your-deployment.vercel.app');
  process.exit(1);
}

if (!token) {
  console.error('Set NOWCODING_SMOKE_TOKEN to seed authenticated smoke data');
  process.exit(1);
}

if (!API_TOKEN_PATTERN.test(token)) {
  console.error(
    'NOWCODING_SMOKE_TOKEN is invalid; expected an nc_live_ token generated by NowCoding',
  );
  process.exit(1);
}

let origin;
let parsedBaseUrl;

try {
  parsedBaseUrl = new URL(baseUrl);
  origin = parsedBaseUrl.origin;
} catch (error) {
  console.error(`Invalid NOWCODING_SMOKE_BASE_URL: ${baseUrl}`);
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}

if (origin === 'null' || !['http:', 'https:'].includes(parsedBaseUrl.protocol)) {
  console.error(`Invalid NOWCODING_SMOKE_BASE_URL origin: ${baseUrl}`);
  process.exit(1);
}

const fixture = buildRcFixture(new Date());

async function postJson(path, payload) {
  let response;
  try {
    response = await fetch(`${origin}${path}`, {
      method: 'POST',
      headers: {
        authorization: `Bearer ${token}`,
        'content-type': 'application/json',
        'x-hostname': fixture.hostname,
      },
      body: JSON.stringify(payload),
    });
  } catch (error) {
    console.error(`POST ${path} failed: ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }

  if (!response.ok) {
    const text = await response.text().catch(() => '');
    console.error(`POST ${path} failed: ${response.status} ${response.statusText}`);
    console.error(text.slice(0, 1000));
    process.exit(1);
  }
}

await postJson('/api/usage/ingest', fixture.ingest);
await postJson('/api/usage/heartbeat', fixture.heartbeat);

console.log(
  `Seeded ${origin}: ${fixture.ingest.buckets.length} buckets, ${
    fixture.ingest.sessions?.length ?? 0
  } sessions, 1 heartbeat`,
);
